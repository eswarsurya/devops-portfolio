#!/usr/bin/env bash
#
# backup.sh - compress a directory, checksum it and ship it to Amazon S3.
#
# Usage:
#   SOURCE_DIR=/var/www BUCKET=my-backups ./backup.sh
#
# Required env vars:
#   SOURCE_DIR   directory to back up
#   BUCKET       target S3 bucket name (no s3:// prefix)
#
# Optional env vars:
#   PREFIX       key prefix inside the bucket          (default: hostname)
#   WORK_DIR     where the archive is built locally    (default: /tmp/s3-backup)
#   KEEP_LOCAL   how many local archives to keep       (default: 3)
#   LOG_FILE     log file path                         (default: $WORK_DIR/backup.log)
#   DRY_RUN      "true" = build archive but skip upload (default: false)
#
# Exit codes: 0 ok, 1 bad config, 2 archive failed, 3 upload failed, 4 verify failed

set -Eeuo pipefail

SOURCE_DIR="${SOURCE_DIR:-}"
BUCKET="${BUCKET:-}"
PREFIX="${PREFIX:-$(hostname -s 2>/dev/null || hostname)}"
WORK_DIR="${WORK_DIR:-/tmp/s3-backup}"
KEEP_LOCAL="${KEEP_LOCAL:-3}"
LOG_FILE="${LOG_FILE:-$WORK_DIR/backup.log}"
DRY_RUN="${DRY_RUN:-false}"

log() {
  # ISO-8601 timestamp + level + message, to stdout and the log file
  local level="$1"; shift
  printf '%s [%s] %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$level" "$*" | tee -a "$LOG_FILE"
}

fail() {
  local code="$1"; shift
  log ERROR "$*"
  exit "$code"
}

# Any unexpected error prints the line number - much easier to debug from cron mail
trap 'log ERROR "unexpected failure at line $LINENO"' ERR

validate() {
  mkdir -p "$WORK_DIR"
  [[ -n "$SOURCE_DIR" ]] || fail 1 "SOURCE_DIR is not set"
  [[ -d "$SOURCE_DIR" ]] || fail 1 "SOURCE_DIR '$SOURCE_DIR' does not exist"
  [[ -n "$BUCKET" ]]     || fail 1 "BUCKET is not set"
  [[ "$KEEP_LOCAL" =~ ^[0-9]+$ ]] || fail 1 "KEEP_LOCAL must be a number"
  if [[ "$DRY_RUN" != "true" ]]; then
    command -v aws >/dev/null 2>&1 || fail 1 "aws CLI not found in PATH"
  fi
}

create_archive() {
  local stamp name
  stamp="$(date -u +%Y%m%dT%H%M%SZ)"
  name="$(basename "$SOURCE_DIR")-${stamp}.tar.gz"
  ARCHIVE="$WORK_DIR/$name"

  log INFO "archiving $SOURCE_DIR -> $ARCHIVE"
  tar -czf "$ARCHIVE" -C "$(dirname "$SOURCE_DIR")" "$(basename "$SOURCE_DIR")" \
    || fail 2 "tar failed"

  # Checksum travels with the archive so a restore can prove integrity
  (cd "$WORK_DIR" && sha256sum "$name" > "$name.sha256")
  log INFO "archive size $(du -h "$ARCHIVE" | cut -f1), sha256 $(cut -d' ' -f1 "$ARCHIVE.sha256")"
}

upload() {
  local key
  key="$PREFIX/$(basename "$ARCHIVE")"
  if [[ "$DRY_RUN" == "true" ]]; then
    log INFO "DRY_RUN: would upload to s3://$BUCKET/$key"
    return 0
  fi

  log INFO "uploading to s3://$BUCKET/$key"
  # SSE-S3 encryption at rest; STANDARD_IA is cheaper for files we rarely read
  aws s3 cp "$ARCHIVE" "s3://$BUCKET/$key" \
      --sse AES256 --storage-class STANDARD_IA --only-show-errors \
    || fail 3 "upload of archive failed"
  aws s3 cp "$ARCHIVE.sha256" "s3://$BUCKET/$key.sha256" \
      --sse AES256 --only-show-errors \
    || fail 3 "upload of checksum failed"

  # Verify the object really landed and the size matches
  local remote_size local_size
  remote_size="$(aws s3api head-object --bucket "$BUCKET" --key "$key" \
                   --query ContentLength --output text)" \
    || fail 4 "object not found after upload"
  local_size="$(stat -c %s "$ARCHIVE")"
  [[ "$remote_size" == "$local_size" ]] \
    || fail 4 "size mismatch: local=$local_size remote=$remote_size"
  log INFO "verified upload ($remote_size bytes)"
}

prune_local() {
  # Keep only the newest $KEEP_LOCAL archives on disk
  local old
  # shellcheck disable=SC2012  # archive names are generated by this script, no odd characters
  old="$(ls -1t "$WORK_DIR"/*.tar.gz 2>/dev/null | tail -n +"$((KEEP_LOCAL + 1))" || true)"
  if [[ -n "$old" ]]; then
    while IFS= read -r f; do
      rm -f -- "$f" "$f.sha256"
      log INFO "pruned local $f"
    done <<< "$old"
  fi
}

main() {
  validate
  log INFO "backup started (source=$SOURCE_DIR bucket=$BUCKET prefix=$PREFIX dry_run=$DRY_RUN)"
  create_archive
  upload
  prune_local
  log INFO "backup finished OK"
}

main "$@"
